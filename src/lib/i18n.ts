const DICTIONARIES: Record<Locale, Dict> = { 'zh-CN': zh, en }

/** 支持的语言（预留泰、韩、日时在此登记） */
export const LOCALES: Array<{ key: Locale; label: string }> = [
  { key: 'zh-CN', label: '简体中文' },
  { key: 'en', label: 'English' },
]

/**
 * 取文案
 * @param locale 当前语言
 * @param key 文案键
 * @param vars 占位符变量（{name} / {count}）
 */
export function t(locale: string, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTIONARIES[(locale === 'en' ? 'en' : 'zh-CN') as Locale]
  let text = dict[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}
